from datetime import date, datetime
from typing import Any, List, Optional, Union
from pydantic import BaseModel, ConfigDict
from app.models import Bureau, CaseCategory, CaseStatus, ConfidenceBand, EventType, Priority, Region, ReviewStatus


class InstitutionMini(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    permanent_id: str
    name: str
    region: str


class InstitutionRead(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: int
    permanent_id: str
    name: str
    address: Optional[str] = None
    region: str
    state: Optional[str] = None
    type: Optional[str] = None


class InstitutionListResponse(BaseModel):
    items: List[InstitutionRead]
    total: int
    page: int
    page_size: int


class CaseSummaryRead(BaseModel):
    """Restricted case view visible across bureaus for Bureau Officers (Section 3)."""
    model_config = ConfigDict(from_attributes=True)

    case_no: str
    bureau: str
    category: str
    status: str
    received_date: date


class CaseRead(BaseModel):
    """Full case object representation per Section 10 of PRD."""
    model_config = ConfigDict(from_attributes=True)

    case_no: str
    institution: InstitutionMini
    bureau: str
    category: str
    description: str
    received_date: date
    status: str
    assigned_officer: Optional[str] = None
    last_action: Optional[str] = None
    last_action_date: Optional[date] = None
    next_action: Optional[str] = None
    expected_disposal_date: Optional[date] = None
    overdue: bool
    priority: str


class CaseListResponse(BaseModel):
    """Paginated case list response model."""
    items: List[Union[CaseRead, CaseSummaryRead]]
    total: int
    page: int
    page_size: int


class InstitutionDetailRead(BaseModel):
    """Institution profile with cases and open overlaps per PRD Section 10."""
    model_config = ConfigDict(from_attributes=True)

    id: int
    permanent_id: str
    name: str
    address: Optional[str] = None
    region: str
    state: Optional[str] = None
    type: Optional[str] = None
    cases: List[Union[CaseRead, CaseSummaryRead]] = []
    open_overlaps: List[Any] = []


class CaseCreate(BaseModel):
    """Payload for creating a new case (POST /cases).

    case_no is auto-generated by the backend from the counters table.
    institution must be identified by its permanent_id.
    """
    permanent_id: str
    bureau: Bureau
    category: CaseCategory
    description: str
    received_date: date
    assigned_officer: Optional[str] = None
    next_action: Optional[str] = None
    expected_disposal_date: Optional[date] = None
    priority: Priority = Priority.MEDIUM


class CasePatch(BaseModel):
    """Payload for updating editable case fields (PATCH /cases/{case_no}).

    Per PRD Section 10: only next_action, expected_disposal_date,
    assigned_officer, and priority may be patched directly.
    All other changes go through events.
    """
    next_action: Optional[str] = None
    expected_disposal_date: Optional[date] = None
    assigned_officer: Optional[str] = None
    priority: Optional[Priority] = None


class EventCreate(BaseModel):
    """Payload for creating a case event."""
    event_type: EventType
    to_status: Optional[CaseStatus] = None
    to_bureau: Optional[Bureau] = None
    remarks: Optional[str] = None
    attachment_ref: Optional[str] = None


class EventRead(BaseModel):
    """Representation of an event per Section 10 of PRD."""
    model_config = ConfigDict(from_attributes=True)

    id: int
    ts: datetime
    actor: str
    bureau: Bureau
    event_type: EventType
    from_bureau: Optional[Bureau] = None
    to_bureau: Optional[Bureau] = None
    from_status: Optional[CaseStatus] = None
    to_status: Optional[CaseStatus] = None
    remarks: Optional[str] = None
    attachment_ref: Optional[str] = None


class AlertRead(BaseModel):
    """Alert response model matching PRD Section 10 contract."""
    model_config = ConfigDict(from_attributes=True)

    id: int
    type: str
    case_id: Optional[int] = None
    case_no: Optional[str] = None
    link_id: Optional[int] = None
    message: str
    priority: str
    status: str
    created_at: datetime
    due_at: Optional[datetime] = None


class AlertListResponse(BaseModel):
    """Paginated alert list response model."""
    items: list[AlertRead]
    total: int
    page: int
    page_size: int


class OverlapCaseMini(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    case_no: str
    bureau: str
    status: str


class OverlapRead(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: int
    band: str
    review_status: str
    reasons: List[str] = []
    case_a: OverlapCaseMini
    case_b: OverlapCaseMini
    reviewed_by: Optional[str] = None
    reviewed_at: Optional[datetime] = None
    note: Optional[str] = None


class OverlapListResponse(BaseModel):
    items: List[OverlapRead]
    total: int
    page: int
    page_size: int


class OverlapScanResponse(BaseModel):
    created: int


class OverlapReviewRequest(BaseModel):
    decision: ReviewStatus
    note: Optional[str] = None


class ManualVerificationItem(BaseModel):
    id: str
    case_no: Optional[str] = None
    case_id: Optional[int] = None
    institution_id: Optional[int] = None
    institution_name: str
    permanent_id: Optional[str] = None
    issue_type: str
    reason: str
    bureau: Optional[str] = None
    received_date: Optional[str] = None
    status: Optional[str] = None


class ManualVerificationResponse(BaseModel):
    total: int
    items: List[ManualVerificationItem]
