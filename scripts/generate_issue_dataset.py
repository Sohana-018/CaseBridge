# Description templates. Issue cases use different templates so the wording is
# genuinely paraphrased; the shared phrase/object keeps the underlying issue
# identifiable.
TEMPLATES = [
    "Complaint regarding {phrase} in the {obj}.",
    "{obj} reported for {phrase} by a group of students.",
    "Allegation of {phrase} concerning the {obj}.",
    "Inspection note on {phrase} at the {obj}.",
    "Grievance about {phrase} affecting the {obj}.",
    "Written complaint highlights {phrase} in the {obj}.",
]

ALT_CATEGORY_TEMPLATES = [
    "Approval review flagged {phrase} in the {obj}.",
    "Compliance audit recorded {phrase} at the {obj}.",
    "Inspection of the {obj} raised {phrase} under a different section.",
]

# Deliberately low-overlap paraphrases: same hidden issue, almost no shared
# wording. These stop the evaluation from rewarding keyword matching alone and
# produce genuine false negatives for a description-based engine.
LOW_OVERLAP_TEMPLATES = [
    "Written representation regarding academic standards; reviewers requested a consolidated response.",
    "A student group raised concerns about the quality of instruction and asked for an inquiry.",
    "Supervision note refers to procedural gaps; supporting papers were requested from the section.",
    "Complaint about institutional practices forwarded to the concerned division for examination.",
    "Inspection observation recorded deficiencies and sought a compliance report.",
]

REGIONS = [Region.NORTH, Region.SOUTH, Region.EAST, Region.WEST, Region.CENTRAL]
STATES = {
    Region.NORTH: ["Haryana", "Punjab", "Delhi", "Uttar Pradesh"],
    Region.SOUTH: ["Karnataka", "Tamil Nadu", "Telangana", "Kerala"],
    Region.EAST: ["West Bengal", "Odisha", "Bihar", "Jharkhand"],
    Region.WEST: ["Maharashtra", "Gujarat", "Rajasthan", "Goa"],
    Region.CENTRAL: ["Madhya Pradesh", "Chhattisgarh", "Uttarakhand", "Jharkhand"],
}
NAME_PREFIXES = ["Sunrise", "National", "Central", "Western", "Eastern", "Northern",
                 "Southern", "Metro", "Heritage", "Pioneer", "Crescent", "Summit",
                 "Horizon", "Capitol", "Riverside"]
NAME_TYPES = ["Institute of Technology", "Polytechnic College", "Academy of Management",
              "College of Engineering", "Institute of Science", "Pharmacy College"]


@dataclass
class GeneratedCase:
    case_no: str
    institution_key: str
    institution_id: int
    bureau: Bureau
    category: CaseCategory
    description: str
    received_date: date
    status: CaseStatus
    assigned_officer: str
    expected_disposal_date: Optional[date]
    priority: Priority
    issue_id: str
    issue_topic: str
    low_overlap: bool = False
    created_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))


def describe(topic: Topic, obj: str, phrase_index: int, template_index: int,
             alt_category: bool = False) -> str:
    phrase = topic.phrases[phrase_index % len(topic.phrases)]
    templates = ALT_CATEGORY_TEMPLATES if alt_category else TEMPLATES
    template = templates[template_index % len(templates)]
    text = template.format(phrase=phrase, obj=obj)
    return text[0].upper() + text[1:]


def pick_alt_category(rng: random.Random, primary: CaseCategory) -> CaseCategory:
    """Pick a category that is *not* related to primary (a hard positive)."""
    options = [c for c in CATEGORIES if not categories_related(c, primary)]
    return rng.choice(options)


def build_institutions() -> List[Dict[str, object]]:
    institutions: List[Dict[str, object]] = []
    for i in range(N_INSTITUTIONS):
        region = REGIONS[i % len(REGIONS)]
        prefix = NAME_PREFIXES[i % len(NAME_PREFIXES)]
        suffix = NAME_TYPES[(i // len(NAME_PREFIXES)) % len(NAME_TYPES)]
        name = f"{prefix} {suffix} {i + 1:02d} (demo)"
        state = STATES[region][i % len(STATES[region])]
        institutions.append(
            {
                "permanent_id": f"EVAL-{i + 1:04d}",
                "name": name,
                "address": f"Demo Campus Road, {state}",
                "region": region,
                "state": state,
                "type": suffix.split()[-1],
            }
        )
    return institutions


def main() -> None:
    rng = random.Random(SEED)
    EVAL_DIR.mkdir(parents=True, exist_ok=True)

    institutions = build_institutions()
    generated: List[GeneratedCase] = []
    used_descriptions: Dict[str, set] = {}
    bureau_counters: Dict[str, int] = {}

    issue_counter = 0
    institution_rows: List[Tuple[int, Dict[str, object]]] = []
    for idx, inst in enumerate(institutions, start=1):
        inst_key = str(inst["permanent_id"])
        inst_id = idx
        institution_rows.append((inst_id, inst))
        used_descriptions[inst_key] = set()

        # Two genuine issues per institution: one with 3 cases, one with 2.
        topic_a, topic_b = rng.sample(TOPICS, 2)
        # Half the time force a same-category/different-issue hard negative.
        if rng.random() < 0.5:
            topic_b = Topic(
                key=topic_b.key,
                category=topic_a.category,
                phrases=topic_b.phrases,
                objects=topic_b.objects,
            )

        issues_spec = [
            (topic_a, 3),
            (topic_b, 2),
        ]
        issue_cases_here: List[GeneratedCase] = []
        for topic, n_cases in issues_spec:
            issue_counter += 1
            issue_id = f"ISS-{issue_counter:04d}"
            obj = rng.choice(topic.objects)
            bureaus = rng.sample(BUREAUS, n_cases)
            base_date = ANCHOR - timedelta(days=rng.randint(25, 250))
            # One case may be filed under a different (unrelated) category and
            # one case may use a deliberately low-overlap paraphrase.
            alt_index = 1 if rng.random() < 0.5 else None
            low_overlap_index: Optional[int] = None
            if n_cases >= 3 and rng.random() < 0.5:
                low_overlap_index = 2
            elif n_cases == 2 and rng.random() < 0.35:
                low_overlap_index = 1

            for i in range(n_cases):
                bureau = bureaus[i]
                alt = (i == alt_index)
                category = pick_alt_category(rng, topic.category) if alt else topic.category

                if i == low_overlap_index:
                    description = LOW_OVERLAP_TEMPLATES[rng.randrange(len(LOW_OVERLAP_TEMPLATES))]
                else:
                    description = describe(
                        topic, obj, phrase_index=i, template_index=i, alt_category=alt
                    )
                # Ensure no duplicate wording inside the institution.
                while description in used_descriptions[inst_key]:
                    if i == low_overlap_index:
                        description = LOW_OVERLAP_TEMPLATES[rng.randrange(len(LOW_OVERLAP_TEMPLATES))]
                    else:
                        description = describe(
                            topic, obj, phrase_index=i + 1, template_index=i + 2, alt_category=alt
                        )
                used_descriptions[inst_key].add(description)

                received = base_date + timedelta(days=rng.randint(0, 40))
                bureau_key = bureau.value
                bureau_counters[bureau_key] = bureau_counters.get(bureau_key, 0) + 1
                case_no = f"{BUREAU_PREFIX[bureau_key]}-{YEAR}-{bureau_counters[bureau_key]:05d}"

                status = rng.choice(
                    [CaseStatus.PENDING, CaseStatus.UNDER_PROCESS, CaseStatus.UNDER_PROCESS]
                )
                case = GeneratedCase(
                    case_no=case_no,
                    institution_key=inst_key,
                    institution_id=inst_id,
                    bureau=bureau,
                    category=category,
                    description=description,
                    received_date=received,
                    status=status,
                    assigned_officer=f"Officer {rng.randint(100, 999)} (demo)",
                    expected_disposal_date=received + timedelta(days=rng.randint(30, 120)),
                    priority=rng.choice([Priority.LOW, Priority.MEDIUM, Priority.HIGH]),
                    issue_id=issue_id,
                    issue_topic=topic.key,
                )
                case.low_overlap = (i == low_overlap_index)
                issue_cases_here.append(case)

        # Fillers: unique issues (never related to anything). Some deliberately
        # share the issue category to create same-category/different-issue pairs.
        n_fillers = CASES_PER_INSTITUTION - len(issue_cases_here)
        for _ in range(n_fillers):
            topic = rng.choice([t for t in TOPICS if t.key not in {topic_a.key, topic_b.key}])
            filler_category = topic_a.category if rng.random() < 0.5 else topic.category
            obj = rng.choice(topic.objects)
            description = describe(
                topic, obj, phrase_index=rng.randrange(3), template_index=rng.randrange(len(TEMPLATES))
            )
            while description in used_descriptions[inst_key]:
                description = describe(
                    topic, obj, phrase_index=rng.randrange(3), template_index=rng.randrange(len(TEMPLATES))
                )
            used_descriptions[inst_key].add(description)

            bureau = rng.choice(BUREAUS)
            bureau_key = bureau.value
            bureau_counters[bureau_key] = bureau_counters.get(bureau_key, 0) + 1
            case_no = f"{BUREAU_PREFIX[bureau_key]}-{YEAR}-{bureau_counters[bureau_key]:05d}"
            issue_counter += 1
            issue_id = f"FLR-{issue_counter:04d}"

            received = ANCHOR - timedelta(days=rng.randint(0, 330))
            status = rng.choices(
                [CaseStatus.PENDING, CaseStatus.UNDER_PROCESS, CaseStatus.TRANSFERRED,
                 CaseStatus.ESCALATED, CaseStatus.DISPOSED],
                weights=[3, 4, 1, 1, 1],
            )[0]
            issue_cases_here.append(
                GeneratedCase(
                    case_no=case_no,
                    institution_key=inst_key,
                    institution_id=inst_id,
                    bureau=bureau,
                    category=filler_category,
                    description=description,
                    received_date=received,
                    status=status,
                    assigned_officer=f"Officer {rng.randint(100, 999)} (demo)",
                    expected_disposal_date=received + timedelta(days=rng.randint(30, 120)),
                    priority=rng.choice([Priority.LOW, Priority.MEDIUM, Priority.HIGH]),
                    issue_id=issue_id,
                    issue_topic=topic.key,
                )
            )

        generated.extend(issue_cases_here)

    # ------------------------------------------------------------------
    # Labelled pairs: every same-institution, cross-Bureau pair.
    # The label depends ONLY on issue_id equality.
    # ------------------------------------------------------------------
    by_institution: Dict[str, List[GeneratedCase]] = {}
    for case in generated:
        by_institution.setdefault(case.institution_key, []).append(case)

    pair_rows: List[Tuple[str, str, str]] = []
    hard_same_category_negative = 0
    hard_different_category_positive = 0
    related_same_category = 0
    related_related_category = 0
    related_with_low_overlap = 0

    for cases in by_institution.values():
        for a, b in combinations(cases, 2):
            if a.bureau == b.bureau:
                continue
            first, second = sorted((a, b), key=lambda c: c.case_no)
            related = first.issue_id == second.issue_id
            pair_rows.append((first.case_no, second.case_no, "related" if related else "not_related"))
            if related:
                if first.low_overlap or second.low_overlap:
                    related_with_low_overlap += 1
                if first.category == second.category:
                    related_same_category += 1
                elif categories_related(first.category, second.category):
                    related_related_category += 1
                else:
                    hard_different_category_positive += 1
            elif first.category == second.category:
                hard_same_category_negative += 1

    pair_rows.sort(key=lambda row: (row[0], row[1]))

    # ------------------------------------------------------------------
    # Write CSVs
    # ------------------------------------------------------------------
    with open(EVAL_DIR / "institutions.csv", "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["id", "permanent_id", "name", "address", "region", "state", "type"])
        for inst_id, inst in institution_rows:
            writer.writerow([
                inst_id, inst["permanent_id"], inst["name"], inst["address"],
                inst["region"].value, inst["state"], inst["type"],
            ])

    with open(EVAL_DIR / "cases.csv", "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow([
            "id", "case_no", "institution_id", "bureau", "category", "description",
            "received_date", "status", "assigned_officer", "last_action",
            "last_action_date", "next_action", "expected_disposal_date", "priority",
            "created_at",
        ])
        for idx, case in enumerate(generated, start=1):
            writer.writerow([
                idx, case.case_no, case.institution_id, case.bureau.value,
                case.category.value, case.description, case.received_date.isoformat(),
                case.status.value, case.assigned_officer, "", "", "",
                case.expected_disposal_date.isoformat() if case.expected_disposal_date else "",
                case.priority.value, case.created_at.isoformat(),
            ])

    with open(EVAL_DIR / "hidden_issues.csv", "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["case_no", "issue_id", "issue_topic"])
        for case in sorted(generated, key=lambda c: c.case_no):
            writer.writerow([case.case_no, case.issue_id, case.issue_topic])

    with open(LABELLED_PATH, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["case_a", "case_b", "label"])
        writer.writerows(pair_rows)

    # ------------------------------------------------------------------
    # Build the evaluation database (no issue_id column anywhere).
    # ------------------------------------------------------------------
    if EVAL_DB.exists():
        EVAL_DB.unlink()
    engine = create_engine(
        f"sqlite:///{EVAL_DB.as_posix()}", connect_args={"check_same_thread": False}
    )
    SQLModel.metadata.create_all(engine)
    with Session(engine) as session:
        for inst_id, inst in institution_rows:
            session.add(Institution(id=inst_id, **inst))
        session.flush()
        for idx, case in enumerate(generated, start=1):
            session.add(
                Case(
                    id=idx,
                    case_no=case.case_no,
                    institution_id=case.institution_id,
                    bureau=case.bureau,
                    category=case.category,
                    description=case.description,
                    received_date=case.received_date,
                    status=case.status,
                    assigned_officer=case.assigned_officer,
                    expected_disposal_date=case.expected_disposal_date,
                    priority=case.priority,
                    created_at=case.created_at,
                )
            )
        session.commit()

    # ------------------------------------------------------------------
    # Report counts (not just decimals)
    # ------------------------------------------------------------------
    related = sum(1 for _, _, label in pair_rows if label == "related")
    not_related = len(pair_rows) - related
    issue_case_counts: Dict[str, int] = {}
    for case in generated:
        issue_case_counts[case.issue_id] = issue_case_counts.get(case.issue_id, 0) + 1
    multi_case_issues = sum(1 for count in issue_case_counts.values() if count > 1)

    print("Issue-based evaluation corpus (synthetic)")
    print(f"  institutions:                 {len(institutions)}")
    print(f"  cases:                        {len(generated)}")
    print(f"  hidden issues (all):          {len(issue_case_counts)}")
    print(f"  multi-case issues:            {multi_case_issues}")
    print(f"  low-overlap paraphrases:      {sum(1 for c in generated if c.low_overlap)}")
    print(f"  labelled pairs:               {len(pair_rows)}")
    print(f"    related (share issue_id):   {related}")
    print(f"    not_related:                {not_related}")
    print(f"  hard positives (same issue, different category): {hard_different_category_positive}")
    print(f"  related pairs, same category:                    {related_same_category}")
    print(f"  related pairs, related category:                 {related_related_category}")
    print(f"  hard negatives (same category, different issue): {hard_same_category_negative}")
    print(f"  related pairs involving a low-overlap paraphrase: {related_with_low_overlap}")
    print()
    print(f"  database: {EVAL_DB}")
    print(f"  labels:   {LABELLED_PATH}")
    print(f"  issue map (hidden): {EVAL_DIR / 'hidden_issues.csv'}")
    print("  Note: labels come only from issue_id; metadata was never used to label.")


if __name__ == "__main__":
    main()
