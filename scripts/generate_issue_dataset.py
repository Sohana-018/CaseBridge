# Mirrors the engine's related-category map. Used ONLY to select hard
# different-category/same-issue cases (never to assign labels).
RELATED_CATEGORIES = [
    {CaseCategory.INFRASTRUCTURE, CaseCategory.APPROVAL},
    {CaseCategory.FACULTY, CaseCategory.OTHER},
    {CaseCategory.ADMISSION, CaseCategory.EXAMINATION},
    {CaseCategory.FEE_REFUND, CaseCategory.ADMISSION},
]


def categories_related(a: CaseCategory, b: CaseCategory) -> bool:
    if a == b:
        return True
    return {a, b} in RELATED_CATEGORIES


@dataclass(frozen=True)
class Topic:
    key: str
    category: CaseCategory
    phrases: Tuple[str, str, str]
    objects: Tuple[str, str, str, str]


