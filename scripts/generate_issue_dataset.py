#!/usr/bin/env python3
"""Build a non-circular overlap evaluation corpus from hidden issues.

Why this script exists
----------------------
The previous ``data/labelled_pairs.csv`` was generated by applying the same
category/status rules that the detection engine uses. That made the evaluation
circular: labels could be predicted from metadata alone, and descriptions were
never used.

This generator works the other way round:

1. It invents hidden ``issue_id`` values (kept only in
   ``data/eval/hidden_issues.csv``, never in the database or API).
2. Each issue is expressed as 2-3 cases in *different* Bureaus, with
   paraphrased descriptions of the same underlying complaint.
3. Hard cases are deliberate:
   - same category, different issue  -> not_related
   - different category, same issue  -> related
4. ``label`` is derived **only** from whether the two cases share an
   ``issue_id``. Category, status, Bureau and text similarity are never used to
   assign a label.

Outputs
-------
- ``backend/casebridge_eval.db``     evaluation database (gitignored)
- ``data/eval/institutions.csv``
- ``data/eval/cases.csv``
- ``data/eval/hidden_issues.csv``    case_no -> issue_id (ground truth)
- ``data/labelled_pairs.csv``        all same-institution, cross-Bureau pairs

All data is synthetic. Run from the repository root:

    python scripts/generate_issue_dataset.py
"""

