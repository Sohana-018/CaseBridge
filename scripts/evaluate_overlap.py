#!/usr/bin/env python3
"""Evaluate the overlap engine on the issue-based ground truth (Phase 12).

The labels in ``data/labelled_pairs.csv`` come only from hidden ``issue_id``
values generated by ``scripts/generate_issue_dataset.py``; they are not derived
from category, status, Bureau or text similarity.

Protocol:
1. Institution-level split: 45 institutions are split into 23 Development and
   22 Test (held out) using a fixed seed (saved to data/eval/institution_split.json).
2. Unsupervised TF-IDF representation: fit once across all case descriptions in
   the corpus using fixed settings (ngram_range=(1, 2), stop_words='english', min_df=1).
   Fitting unsupervised TF-IDF across the whole corpus is standard and acceptable
   because it uses no labels.
3. Tuning objective: Highest precision on Dev with recall >= 0.50 (balancing
   precision and recall on detectable text-overlapping pairs, given that ~26% of
   synthetic ground-truth pairs have 0.0 cosine similarity due to low-overlap paraphrases).
   The central demo pair staying High is a sanity check, not part of the objective.
4. Single evaluation run on the held-out Test split.
5. All counts (TP, FP, FN, TN, and related pairs per band) reported alongside decimals.

Usage (from repository root):
    python scripts/evaluate_overlap.py
    python scripts/evaluate_overlap.py --db backend/casebridge_eval_fresh.db --labelled data/eval_fresh/labelled_pairs.csv --fresh-check
"""

from __future__ import annotations

import argparse
import csv
import json
import random
import sys
from collections import Counter
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Set, Tuple

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))

from sqlmodel import Session, create_engine, select  # noqa: E402

from app.models import Case, ConfidenceBand  # noqa: E402
from app.services.overlap import (  # noqa: E402
    get_or_fit_vectorizer,
    is_candidate_pair,
    score_pair,
)

DEFAULT_DB = ROOT / "backend" / "casebridge_eval.db"
DEFAULT_LABELLED = ROOT / "data" / "labelled_pairs.csv"
DEFAULT_SPLIT_FILE = ROOT / "data" / "eval" / "institution_split.json"
SPLIT_SEED = 42


@dataclass
class Row:
    """One labelled pair and the engine's prediction."""
    case_a: str
    case_b: str
    label: str
    band: Optional[ConfidenceBand]
    candidate: bool
    same_category: bool
    reasons: List[str]
    baseline_positive: bool
    institution_id: int

    @property
    def predicted(self) -> bool:
        return self.band in (ConfidenceBand.MEDIUM, ConfidenceBand.HIGH)

    @property
    def actual(self) -> bool:
        return self.label == "related"


def load_pairs(path: Path) -> List[Tuple[str, str, str]]:
    with open(path, newline="", encoding="utf-8") as handle:
        return [
            (row["case_a"].strip(), row["case_b"].strip(), row["label"].strip())
            for row in csv.DictReader(handle)
        ]


def load_cases(db_path: Path) -> Dict[str, Case]:
    engine = create_engine(
        f"sqlite:///{db_path.as_posix()}", connect_args={"check_same_thread": False}
    )
    with Session(engine) as session:
        return {case.case_no: case for case in session.exec(select(Case)).all()}


def get_institution_split(
    cases: Dict[str, Case], split_file: Optional[Path] = None, seed: int = SPLIT_SEED
) -> Tuple[Set[int], Set[int]]:
    """Partition institutions deterministically into Dev and Test."""
    if split_file and split_file.exists():
        with open(split_file, "r", encoding="utf-8") as f:
            data = json.load(f)
            return set(data["dev_institutions"]), set(data["test_institutions"])

    all_inst_ids = sorted(list({c.institution_id for c in cases.values()}))
    rng = random.Random(seed)
    shuffled = list(all_inst_ids)
    rng.shuffle(shuffled)
    midpoint = len(shuffled) // 2 + (len(shuffled) % 2)  # 23 dev, 22 test for 45
    dev_ids = set(shuffled[:midpoint])
    test_ids = set(shuffled[midpoint:])

    if split_file:
        split_file.parent.mkdir(parents=True, exist_ok=True)
        with open(split_file, "w", encoding="utf-8") as f:
            json.dump(
                {
                    "seed": seed,
                    "total_institutions": len(all_inst_ids),
                    "dev_count": len(dev_ids),
                    "test_count": len(test_ids),
                    "dev_institutions": sorted(list(dev_ids)),
                    "test_institutions": sorted(list(test_ids)),
                },
                f,
                indent=2,
            )

    return dev_ids, test_ids


def build_rows(
    labelled: Sequence[Tuple[str, str, str]],
    cases: Dict[str, Case],
    vectorizer=None,
) -> Tuple[List[Row], int]:
    rows: List[Row] = []
    skipped = 0
    for case_a_no, case_b_no, label in labelled:
        case_a = cases.get(case_a_no)
        case_b = cases.get(case_b_no)
        if not case_a or not case_b:
            skipped += 1
            continue

        candidate = is_candidate_pair(case_a, case_b)
        band: Optional[ConfidenceBand] = None
        reasons: List[str] = []
        if candidate:
            band, reasons = score_pair(case_a, case_b, vectorizer=vectorizer)

        rows.append(
            Row(
                case_a=case_a_no,
                case_b=case_b_no,
                label=label,
                band=band,
                candidate=candidate,
                same_category=case_a.category == case_b.category,
                reasons=reasons,
                baseline_positive=(
                    case_a.institution_id == case_b.institution_id
                    and case_a.bureau != case_b.bureau
                ),
                institution_id=case_a.institution_id,
            )
        )
    return rows, skipped


def confusion(rows: Sequence[Row], predicate=None) -> Dict[str, int]:
    if predicate is None:
        predicate = lambda row: row.predicted  # noqa: E731
    tp = sum(1 for row in rows if predicate(row) and row.actual)
    fp = sum(1 for row in rows if predicate(row) and not row.actual)
    fn = sum(1 for row in rows if not predicate(row) and row.actual)
    tn = sum(1 for row in rows if not predicate(row) and not row.actual)
    return {"tp": tp, "fp": fp, "fn": fn, "tn": tn}


def prf(tp: int, fp: int, fn: int) -> Tuple[float, float, float]:
    precision = tp / (tp + fp) if (tp + fp) else 0.0
    recall = tp / (tp + fn) if (tp + fn) else 0.0
    f1 = 2 * precision * recall / (precision + recall) if (precision + recall) else 0.0
    return precision, recall, f1


def line(name: str, counts: Dict[str, int]) -> str:
    precision, recall, f1 = prf(counts["tp"], counts["fp"], counts["fn"])
    return (
        f"{name:<26} P={precision:.3f}  R={recall:.3f}  F1={f1:.3f}  |  "
        f"TP={counts['tp']:3d}  FP={counts['fp']:3d}  FN={counts['fn']:3d}  TN={counts['tn']:3d}"
    )


def band_breakdown(rows: Sequence[Row], split_name: str) -> None:
    high_tp = sum(1 for r in rows if r.actual and r.band == ConfidenceBand.HIGH)
    high_fp = sum(1 for r in rows if not r.actual and r.band == ConfidenceBand.HIGH)
    med_tp = sum(1 for r in rows if r.actual and r.band == ConfidenceBand.MEDIUM)
    med_fp = sum(1 for r in rows if not r.actual and r.band == ConfidenceBand.MEDIUM)
    low_tp = sum(1 for r in rows if r.actual and r.band == ConfidenceBand.LOW)
    low_fp = sum(1 for r in rows if not r.actual and r.band == ConfidenceBand.LOW)
    not_cand = sum(1 for r in rows if not r.candidate)

    print(f"  {split_name}:")
    print(f"    High band:    TP={high_tp:2d}, FP={high_fp:2d} (total {high_tp+high_fp})")
    print(f"    Medium band:  TP={med_tp:2d}, FP={med_fp:2d} (total {med_tp+med_fp})")
    print(f"    Low band:     FN={low_tp:2d}, TN={low_fp:2d} (total {low_tp+low_fp})")
    print(f"    Non-candidate: {not_cand}")
    print(f"    Related pairs in band: High={high_tp}, Medium={med_tp}, Low/missed={low_tp}")


def main() -> None:
    parser = argparse.ArgumentParser(description="Evaluate overlap detection on issue-based labels.")
    parser.add_argument("--db", type=Path, default=DEFAULT_DB)
    parser.add_argument("--labelled", type=Path, default=DEFAULT_LABELLED)
    parser.add_argument("--split-file", type=Path, default=DEFAULT_SPLIT_FILE)
    parser.add_argument("--fresh-check", action="store_true", help="Running on fresh seed")
    args = parser.parse_args()

    if not args.db.exists():
        raise SystemExit(
            f"Missing evaluation database: {args.db}\n"
            "Run: python scripts/generate_issue_dataset.py"
        )
    if not args.labelled.exists():
        raise SystemExit(f"Missing labelled pairs: {args.labelled}")

    cases = load_cases(args.db)
    labelled = load_pairs(args.labelled)

    # 1. Fit TF-IDF once on ALL case descriptions (unsupervised, no labels used)
    descriptions = [c.description or "" for c in cases.values()]
    vectorizer = get_or_fit_vectorizer(descriptions, force_refit=True)

    # 2. Score all pairs with the corpus vectorizer
    rows, skipped = build_rows(labelled, cases, vectorizer=vectorizer)

    # 3. Partition by institution
    split_file = None if args.fresh_check else args.split_file
    dev_insts, test_insts = get_institution_split(cases, split_file=split_file)

    dev_rows = [r for r in rows if r.institution_id in dev_insts]
    test_rows = [r for r in rows if r.institution_id in test_insts]

    related = sum(1 for row in rows if row.actual)
    not_related = len(rows) - related
    candidates = sum(1 for row in rows if row.candidate)

    print("================================================================================")
    print("CaseBridge Overlap Evaluation - Non-Circular Issue-Based Ground Truth")
    if args.fresh_check:
        print("  MODE: FRESH-SEED STABILITY CHECK (Tests threshold stability, not realism)")
    print("================================================================================")
    print(f"  Database:            {args.db}")
    print(f"  Labelled pairs:      {args.labelled}")
    print(f"  Cases in DB:         {len(cases)} across {len(set(c.institution_id for c in cases.values()))} institutions")
    print(f"  Scored pairs:        {len(rows)} (skipped {skipped})")
    print(f"  Related pairs:       {related}")
    print(f"  Not related pairs:   {not_related}")
    print(f"  Candidate pairs:     {candidates}")
    print(f"  Institution split:   Dev={len(dev_insts)} insts ({len(dev_rows)} pairs) | Test={len(test_insts)} insts ({len(test_rows)} pairs)")
    print("  Representation:      TF-IDF fit once on full corpus (unsupervised, uses no labels)")
    print("  Tuning Objective:    Highest Precision on Dev with Recall >= 0.50")
    print("  Decision Threshold:  Flagged if ConfidenceBand >= Medium (sim >= 0.14)")
    print("--------------------------------------------------------------------------------\n")

    overall = confusion(rows)
    dev_counts = confusion(dev_rows)
    test_counts = confusion(test_rows)
    baseline_counts = confusion(rows, lambda row: row.baseline_positive)

    print("METRICS & EXACT COUNTS (TP, FP, FN, TN)")
    print("  " + line("Development Split", dev_counts))
    print("  " + line("Test Split (held-out)", test_counts))
    print("  " + line("All Scored Pairs", overall))
    print("  " + line("Baseline (flag all)", baseline_counts))
    print()

    print("BAND DISTRIBUTION & RELATED PAIRS PER BAND")
    band_breakdown(dev_rows, f"Development Split ({len(dev_rows)} pairs)")
    band_breakdown(test_rows, f"Test Split ({len(test_rows)} pairs)")
    band_breakdown(rows, f"All Pairs ({len(rows)} pairs)")
    print()

    # ---- Error analysis -----------------------------------------------------
    fn_rows = [row for row in rows if not row.predicted and row.actual]
    fp_rows = [row for row in rows if row.predicted and not row.actual]
    fn_filtered = sum(1 for row in fn_rows if not row.candidate)
    fn_low_band = len(fn_rows) - fn_filtered
    fp_same_category = sum(1 for row in fp_rows if row.same_category)
    fp_other_category = len(fp_rows) - fp_same_category

    print("ERROR BREAKDOWN (All Pairs)")
    print(f"  Total False Positives: {len(fp_rows)} (down from 439 in baseline engine)")
    print(f"    - Same category, different issue (metadata match): {fp_same_category}")
    print(f"    - Different category, text similarity match:       {fp_other_category}")
    print(f"  Total False Negatives: {len(fn_rows)}")
    print(f"    - Excluded by candidate rules (disposed/cross-inst): {fn_filtered}")
    print(f"    - Scored Low (low-overlap paraphrases without common words): {fn_low_band}")
    print()


if __name__ == "__main__":
    main()
