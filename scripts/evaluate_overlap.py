#!/usr/bin/env python3
"""Evaluate the overlap engine on the issue-based ground truth (Phase 12).

The labels in ``data/labelled_pairs.csv`` come only from hidden ``issue_id``
values generated by ``scripts/generate_issue_dataset.py``; they are not derived
from category, status, Bureau or text similarity. This makes the evaluation
non-circular.

The detection engine (``backend/app/services/overlap.py``) is used as-is with
its current default thresholds. Nothing is tuned here: the point is to measure
the existing engine against independent labels.

Usage (from the repository root):
    python scripts/generate_issue_dataset.py
    python scripts/evaluate_overlap.py
"""

from __future__ import annotations

import argparse
import csv
import random
import sys
from collections import Counter
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))

from sqlmodel import Session, create_engine, select  # noqa: E402

from app.models import Case, ConfidenceBand  # noqa: E402
from app.services.overlap import is_candidate_pair, score_pair  # noqa: E402

DEFAULT_DB = ROOT / "backend" / "casebridge_eval.db"
DEFAULT_LABELLED = ROOT / "data" / "labelled_pairs.csv"
SPLIT_SEED = 42


@dataclass
class Row:
    """One labelled pair and the engine's prediction."""
    case_a: str
    case_b: str
    label: str
    band: Optional[ConfidenceBand]
    candidate: bool
    same_category: bool
    reasons: List[str]
    baseline_positive: bool

    @property
    def predicted(self) -> bool:
        return self.band in (ConfidenceBand.MEDIUM, ConfidenceBand.HIGH)

    @property
    def actual(self) -> bool:
        return self.label == "related"


def load_pairs(path: Path) -> List[Tuple[str, str, str]]:
    with open(path, newline="", encoding="utf-8") as handle:
        return [
            (row["case_a"].strip(), row["case_b"].strip(), row["label"].strip())
            for row in csv.DictReader(handle)
        ]


def load_cases(db_path: Path) -> Dict[str, Case]:
    engine = create_engine(
        f"sqlite:///{db_path.as_posix()}", connect_args={"check_same_thread": False}
    )
    with Session(engine) as session:
        return {case.case_no: case for case in session.exec(select(Case)).all()}


def build_rows(
    labelled: Sequence[Tuple[str, str, str]], cases: Dict[str, Case]
) -> Tuple[List[Row], int]:
    rows: List[Row] = []
    skipped = 0
    for case_a_no, case_b_no, label in labelled:
        case_a = cases.get(case_a_no)
        case_b = cases.get(case_b_no)
        if not case_a or not case_b:
            skipped += 1
            continue

        candidate = is_candidate_pair(case_a, case_b)
        band: Optional[ConfidenceBand] = None
        reasons: List[str] = []
        if candidate:
            band, reasons = score_pair(case_a, case_b)

        rows.append(
            Row(
                case_a=case_a_no,
                case_b=case_b_no,
                label=label,
                band=band,
                candidate=candidate,
                same_category=case_a.category == case_b.category,
                reasons=reasons,
                baseline_positive=(
                    case_a.institution_id == case_b.institution_id
                    and case_a.bureau != case_b.bureau
                ),
            )
        )
    return rows, skipped


def stratified_split(rows: Sequence[Row], seed: int = SPLIT_SEED) -> Tuple[List[Row], List[Row]]:
    """Deterministic 50/50 split, stratified so both labels appear in each half."""
    rng = random.Random(seed)
    related = [row for row in rows if row.actual]
    not_related = [row for row in rows if not row.actual]
    rng.shuffle(related)
    rng.shuffle(not_related)

    def halves(items: List[Row]) -> Tuple[List[Row], List[Row]]:
        midpoint = len(items) // 2
        return items[:midpoint], items[midpoint:]

    rel_dev, rel_test = halves(related)
    neg_dev, neg_test = halves(not_related)
    return rel_dev + neg_dev, rel_test + neg_test


def confusion(rows: Sequence[Row], predicate=None) -> Dict[str, int]:
    if predicate is None:
        predicate = lambda row: row.predicted  # noqa: E731
    tp = sum(1 for row in rows if predicate(row) and row.actual)
    fp = sum(1 for row in rows if predicate(row) and not row.actual)
    fn = sum(1 for row in rows if not predicate(row) and row.actual)
    tn = sum(1 for row in rows if not predicate(row) and not row.actual)
    return {"tp": tp, "fp": fp, "fn": fn, "tn": tn}


def prf(tp: int, fp: int, fn: int) -> Tuple[float, float, float]:
    precision = tp / (tp + fp) if (tp + fp) else 0.0
    recall = tp / (tp + fn) if (tp + fn) else 0.0
    f1 = 2 * precision * recall / (precision + recall) if (precision + recall) else 0.0
    return precision, recall, f1


def line(name: str, counts: Dict[str, int]) -> str:
    precision, recall, f1 = prf(counts["tp"], counts["fp"], counts["fn"])
    return (
        f"{name:<26} P={precision:.3f}  R={recall:.3f}  F1={f1:.3f}  |  "
        f"TP={counts['tp']:3d}  FP={counts['fp']:3d}  FN={counts['fn']:3d}  TN={counts['tn']:3d}"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description="Evaluate overlap detection on issue-based labels.")
    parser.add_argument("--db", type=Path, default=DEFAULT_DB)
    parser.add_argument("--labelled", type=Path, default=DEFAULT_LABELLED)
    args = parser.parse_args()

    if not args.db.exists():
        raise SystemExit(
            f"Missing evaluation database: {args.db}\n"
            "Run: python scripts/generate_issue_dataset.py"
        )
    if not args.labelled.exists():
        raise SystemExit(f"Missing labelled pairs: {args.labelled}")

    cases = load_cases(args.db)
    labelled = load_pairs(args.labelled)
    rows, skipped = build_rows(labelled, cases)
    dev, test = stratified_split(rows)

    related = sum(1 for row in rows if row.actual)
    not_related = len(rows) - related
    candidates = sum(1 for row in rows if row.candidate)

    print("CaseBridge overlap evaluation - issue-based labels (synthetic data)")
    print(f"  database:            {args.db}")
    print(f"  labelled pairs:      {args.labelled}")
    print(f"  cases in DB:         {len(cases)}")
    print(f"  scored pairs:        {len(rows)}  (skipped {skipped})")
    print(f"  related:             {related}")
    print(f"  not_related:         {not_related}")
    print(f"  candidate pairs:     {candidates}")
    print(f"  split:               dev={len(dev)}  test={len(test)}  (stratified)")
    print("  engine thresholds:   unchanged defaults from services/overlap.py")
    print()

    overall = confusion(rows)
    dev_counts = confusion(dev)
    test_counts = confusion(test)
    baseline_counts = confusion(rows, lambda row: row.baseline_positive)

    print("ALL PAIRS (current engine, >= Medium = flagged)")
    print("  " + line("engine", overall))
    print("  " + line("baseline (same inst/diff Bureau)", baseline_counts))
    print()
    print("DEVELOPMENT HALF")
    print("  " + line("engine", dev_counts))
    print("TEST HALF (held out)")
    print("  " + line("engine", test_counts))
    print()

    # ---- Where do the errors come from? -------------------------------------
    fn_rows = [row for row in rows if not row.predicted and row.actual]
    fp_rows = [row for row in rows if row.predicted and not row.actual]
    fn_filtered = sum(1 for row in fn_rows if not row.candidate)
    fn_low_band = len(fn_rows) - fn_filtered
    fp_same_category = sum(1 for row in fp_rows if row.same_category)
    fp_other_category = len(fp_rows) - fp_same_category

    band_counts = Counter(
        row.band.value if row.band else "not_candidate" for row in rows
    )
    tp_high = sum(1 for row in rows if row.actual and row.band == ConfidenceBand.HIGH)
    tp_medium = sum(1 for row in rows if row.actual and row.band == ConfidenceBand.MEDIUM)
    tp_low = sum(1 for row in rows if row.actual and row.band == ConfidenceBand.LOW)

    print("BAND DISTRIBUTION (all scored pairs)")
    for band in ("high", "medium", "low", "not_candidate"):
        print(f"  {band:<14} {band_counts.get(band, 0)}")
    print()
    print("RELATED PAIRS BY BAND")
    print(f"  high          {tp_high}")
    print(f"  medium        {tp_medium}")
    print(f"  low (missed)  {tp_low}")
    print()
    print("FALSE NEGATIVES (related pairs not flagged): "
          f"{len(fn_rows)}")
    print(f"  excluded by candidate rules (disposed / same Bureau / >365 days): {fn_filtered}")
    print(f"  candidate but scored Low:                                        {fn_low_band}")
    print()
    print("FALSE POSITIVES (not_related pairs flagged): "
          f"{len(fp_rows)}")
    print(f"  same category, different issue (metadata-only match): {fp_same_category}")
    print(f"  different category, text similarity only:             {fp_other_category}")
    print()
    print("INTERPRETATION")
    print("  - Labels come only from hidden issue_id; metadata rules were not used.")
    print("  - Every labelled pair is same-institution and cross-Bureau, so the")
    print("    baseline flags all of them.")
    print("  - A high false-positive count driven by 'same category, different issue'")
    print("    is the circularity the new ground truth was built to expose.")
    print("  - All data is synthetic demo data.")


if __name__ == "__main__":
    main()
